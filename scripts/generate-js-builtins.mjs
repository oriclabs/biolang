#!/usr/bin/env node
/** Generate the public JavaScript builtin surface from the shipped WASM module. */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const wasmRoot = path.join(root, "desktop", "public", "wasm");
const packageRoot = path.join(root, "npm");
const wasmModule = process.env.BIOLANG_WASM_MODULE
  ?? path.join(wasmRoot, "bl_wasm.js");
const wasmBinary = process.env.BIOLANG_WASM_BINARY
  ?? path.join(wasmRoot, "bl_wasm_bg.wasm");
const metadata = JSON.parse(readFileSync(
  path.join(root, "desktop", "src", "generated", "builtin-metadata.json"),
  "utf8",
));
const packageVersion = JSON.parse(readFileSync(path.join(packageRoot, "package.json"), "utf8")).version;
if (metadata.languageVersion !== packageVersion) {
  throw new Error(
    `builtin metadata version ${metadata.languageVersion} does not match npm ${packageVersion}`,
  );
}
const metadataByName = new Map(metadata.builtins.map((builtin) => [builtin.name, builtin]));

globalThis.window = globalThis;
globalThis.__blFiles = {};
globalThis.__blFetch = { sync: () => "ERROR:offline JavaScript SDK generation" };

const module_ = await import(pathToFileURL(wasmModule).href);
await module_.default({ module_or_path: readFileSync(wasmBinary) });
module_.init();

const builtins = JSON.parse(module_.list_builtins())
  .map(({ name, arity }) => ({ name, arity }))
  .sort((left, right) => left.name.localeCompare(right.name));

const names = new Set();
for (const builtin of builtins) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(builtin.name)) {
    throw new Error(`WASM builtin '${builtin.name}' is not exportable as a JavaScript name`);
  }
  if (names.has(builtin.name)) throw new Error(`Duplicate WASM builtin '${builtin.name}'`);
  names.add(builtin.name);
}

const reserved = new Set([
  "await", "break", "case", "catch", "class", "const", "continue", "debugger",
  "default", "delete", "do", "else", "enum", "export", "extends", "false",
  "finally", "for", "function", "if", "import", "in", "instanceof", "let",
  "new", "null", "return", "static", "super", "switch", "this", "throw",
  "true", "try", "typeof", "var", "void", "while", "with", "yield",
]);

const js = [
  "// Generated by scripts/generate-js-builtins.mjs. Do not edit by hand.",
  'import { call } from "./dsl.js";',
  "",
];
const dts = [
  "// Generated by scripts/generate-js-builtins.mjs. Do not edit by hand.",
  'import type { BioArgument, BioExpression } from "./dsl.js";',
  "export type BioBuiltin = (...args: BioArgument[]) => BioExpression;",
  "",
];
const sessionMethodNames = new Set([
  "then", "run", "define", "ref", "invoke", "csvExpression", "tableExpression",
  "sequence", "matrixExpression",
  "reset", "builtins", "supports", "variables", "inspectVariable", "exportVariable",
  "registerModule", "runtimeVersion", "formatSource", "tokenize", "diagnostics", "completions",
  "signature", "transpileJavaScript", "import", "validateImport", "qcMetrics",
  "connectSomer", "raw", "dispose",
  "evalValue", "callValue", "setValue", "getValue", "registerFunction",
]);
const sessionDts = [
  "// Generated by scripts/generate-js-builtins.mjs. Do not edit by hand.",
  'import type { BioJsValue, BioMatrixValue, BioSequenceValue, BioTableValue, BioValueHandle } from "./values.js";',
  "",
  "export interface BioLangSessionBuiltinMethods {",
];

for (const { name, arity } of builtins) {
  const local = reserved.has(name) ? `builtin_${name}` : name;
  js.push(`const ${local} = (...args) => call(${JSON.stringify(name)}, ...args);`);
  dts.push(`declare const ${local}: BioBuiltin;`);
  if (reserved.has(name)) {
    js.push(`export { ${local} as ${name} };`);
    dts.push(`export { ${local} as ${name} };`);
  } else {
    js.push(`export { ${name} };`);
    dts.push(`export { ${name} };`);
  }
  if (!sessionMethodNames.has(name)) {
    const details = metadataByName.get(name);
    sessionDts.push(...sessionDocumentation(details));
    sessionDts.push(
      `  ${JSON.stringify(name)}(${sessionParameters(name, arity, details)}): ${sessionReturnType(details?.returnType)};`,
    );
  }
}

js.push(
  "",
  `export const WASM_BUILTIN_NAMES = Object.freeze(${JSON.stringify(builtins.map(({ name }) => name))});`,
);
dts.push("", "export const WASM_BUILTIN_NAMES: readonly string[];");
sessionDts.push("}");

writeFileSync(path.join(packageRoot, "generated-builtins.js"), `${js.join("\n")}\n`);
writeFileSync(path.join(packageRoot, "generated-builtins.d.ts"), `${dts.join("\n")}\n`);
writeFileSync(
  path.join(packageRoot, "generated-session-builtins.d.ts"),
  `${sessionDts.join("\n")}\n`,
);
writeFileSync(
  path.join(packageRoot, "wasm-builtins.json"),
  `${JSON.stringify({ schema: 1, count: builtins.length, builtins }, null, 2)}\n`,
);
console.log(`Generated ${builtins.length} JavaScript builtin wrappers from the WASM module.`);
console.log(
  `Added named parameters and hover documentation for ${builtins.filter(({ name }) => metadataByName.has(name)).length} builtins.`,
);

function sessionDocumentation(details) {
  if (!details) return [];
  const lines = ["  /**"];
  if (details.summary) lines.push(`   * ${documentationText(details.summary)}`);
  if (details.signature) lines.push(`   * BioLang: \`${documentationText(details.signature)}\``);
  if (details.category) lines.push(`   * @category ${documentationText(details.category)}`);
  if (details.example) lines.push(`   * @example ${documentationText(details.example)}`);
  lines.push("   */");
  return lines;
}

function documentationText(value) {
  return String(value).replace(/\r?\n/g, " ").replace(/\*\//g, "*\\/");
}

function sessionParameters(builtinName, arity, details) {
  const match = /^(Exact|Range|AtLeast)\((\d+)(?:,\s*(\d+))?\)$/.exec(arity);
  if (!match) return "...args: unknown[]";
  const kind = match[1];
  const minimum = Number(match[2]);
  const maximum = kind === "Exact" ? minimum : Number(match[3] ?? minimum);
  const rawNames = Array.isArray(details?.parameters) ? details.parameters : [];
  const names = [];
  const count = kind === "AtLeast" ? minimum : maximum;
  for (let index = 0; index < count; index += 1) {
    const raw = String(rawNames[index] ?? "").replace(/\?$/, "");
    let name = validParameterName(raw) ? raw : fallbackParameterName(builtinName, index);
    while (names.includes(name)) name = `${name}${index + 1}`;
    names.push(name);
  }
  const parameters = names.map((name, index) => {
    const optional = index >= minimum && kind !== "AtLeast" ? "?" : "";
    return `${name}${optional}: unknown`;
  });
  if (kind === "AtLeast") parameters.push("...rest: unknown[]");
  return parameters.join(", ");
}

function validParameterName(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) && !reserved.has(name);
}

function fallbackParameterName(builtinName, index) {
  if (index === 0 && ["dna", "rna", "protein"].includes(builtinName)) return "sequence";
  return `arg${index + 1}`;
}

function sessionReturnType(value) {
  const type = String(value ?? "").trim();
  if (!type || type === "null" || /^Value\b/i.test(type)) return "BioJsValue";
  if (/^Nil\b/i.test(type)) return "null";
  if (/^Bool\b/i.test(type)) return "boolean";
  if (/^(Float|number)\b/i.test(type)) return "number";
  if (/^Int\b/i.test(type)) return "number | bigint";
  if (/^Str\|Nil$/i.test(type)) return "string | null";
  if (/^Str\b/i.test(type)) return "string";
  if (/^(DNA|RNA|Protein)\b/i.test(type)) return "BioSequenceValue | BioValueHandle";
  if (/^List\[Float\]/i.test(type)) return "number[] | BioValueHandle";
  if (/^List\[Str\]/i.test(type)) return "string[] | BioValueHandle";
  if (/^List\b/i.test(type)) return "BioJsValue[] | BioValueHandle";
  if (/^Set\b/i.test(type)) return "Set<BioJsValue> | BioValueHandle";
  if (/^(Map|Record)\b/i.test(type)) return "Record<string, BioJsValue> | BioValueHandle";
  if (/^Table\b/i.test(type)) return "BioTableValue | BioValueHandle";
  if (/^(Sparse)?Matrix\b/i.test(type)) return "BioMatrixValue | BioValueHandle";
  return "BioJsValue";
}
